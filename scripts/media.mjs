#!/usr/bin/env node
/**
 * Media pipeline for the studio site.
 *
 *   node scripts/media.mjs fetch    download licensed source files into media-source/ (skips what exists)
 *   node scripts/media.mjs images   optimise stills to responsive WebP + write src/data/media.generated.js
 *   node scripts/media.mjs hero     build the scroll-scrub film, posters and the mobile frame sequence
 *   node scripts/media.mjs stills   cut the before/after demonstration stills from the hero masters
 *   node scripts/media.mjs og       Open Graph card + touch icon from the hero's finished frame
 *   node scripts/media.mjs licenses regenerate MEDIA-LICENSES.md from the manifest
 *   node scripts/media.mjs all
 *
 * Requires ffmpeg on PATH (hero + stills). Sources are Pexels files, see media-manifest.json
 * and MEDIA-LICENSES.md. Outputs go to public/media/ and are the only media that ships.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const ROOT = path.resolve(import.meta.dirname, '..')
const SRC = process.env.MEDIA_SRC || path.join(ROOT, 'media-source')
const PUB = path.join(ROOT, 'public', 'media')
const CACHE = path.join(SRC, '.cache')
const manifest = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, 'media-manifest.json'), 'utf8'))

const ffmpeg = (args) => execFileSync('ffmpeg', ['-v', 'error', '-y', ...args], { stdio: ['ignore', 'inherit', 'inherit'] })
const mkdir = (p) => fs.mkdirSync(p, { recursive: true })
const kb = (f) => `${(fs.statSync(f).size / 1024).toFixed(0)} KB`

/* ------------------------------------------------------------------ fetch */
async function download(url, dest) {
  if (fs.existsSync(dest) && fs.statSync(dest).size > 20000) return false
  mkdir(path.dirname(dest))
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()))
  return true
}

async function fetchSources() {
  for (const p of manifest.photos) {
    const url = `https://images.pexels.com/photos/${p.id}/pexels-photo-${p.id}.jpeg?auto=compress&cs=tinysrgb&w=2000`
    if (await download(url, path.join(SRC, 'photos', `${p.id}.jpg`))) console.log('fetched photo', p.id)
  }
  for (const v of manifest.videos) {
    if (await download(v.file, path.join(SRC, 'video', v.master))) console.log('fetched video', v.id)
  }
}

/* ----------------------------------------------------------------- images */
const WIDTHS = [480, 960, 1600]

async function buildImages() {
  const out = path.join(PUB, 'img')
  mkdir(out)
  const generated = {}
  for (const p of manifest.photos) {
    const file = path.join(SRC, 'photos', `${p.id}.jpg`)
    const base = sharp(file, { failOn: 'none' }).rotate()
    const meta = await base.metadata()
    const { width: w0, height: h0 } = (await sharp(await base.clone().toBuffer()).metadata())
    const widths = [...new Set([...WIDTHS.filter((w) => w < w0), Math.min(WIDTHS.at(-1), w0)])]
    for (const w of widths) {
      await base.clone().resize({ width: w }).webp({ quality: w > 900 ? 74 : 70, effort: 5 }).toFile(path.join(out, `${p.key}-${w}.webp`))
    }
    const px = await base.clone().resize(1, 1).raw().toBuffer()
    const color = '#' + [...px.subarray(0, 3)].map((n) => n.toString(16).padStart(2, '0')).join('')
    generated[p.key] = { w: w0, h: h0, widths, alt: p.alt, pos: p.pos || '50% 35%', color, pexelsId: p.id }
    void meta
  }
  const body = `// GENERATED by scripts/media.mjs, do not edit by hand.\nexport const MEDIA = ${JSON.stringify(generated, null, 2)}\n`
  fs.writeFileSync(path.join(ROOT, 'src', 'data', 'media.generated.js'), body)
  console.log(`images: ${Object.keys(generated).length} stills`)
}

/* ------------------------------------------------------------------- hero */
// Chapter map (source seconds): 1 prep (A 0.4-6.6) / 2 lips (B 2.5-11.5 @1.3x) / 3 glow (B 21-30 @1.3x) / 4 reveal (B 41-47.2)
// 0.3s crossfades between chapters. Joins at 5.9, 12.523, 19.146 on the output timeline. Total 25.36s.
const GRADE = 'hqdn3d=2.5:2:4:3,eq=contrast=1.06:saturation=1.08:brightness=0.025:gamma=1.04,colorbalance=rs=0.03:bs=-0.03:rm=0.035:bm=-0.025:rh=0.02:bh=-0.015'
const JOIN = '[s1][s2]xfade=transition=fade:duration=0.3:offset=5.9[x1];[x1][s3]xfade=transition=fade:duration=0.3:offset=12.523[x2];[x2][s4]xfade=transition=fade:duration=0.3:offset=19.146,format=yuv420p[v]'

function graph(crops, size) {
  const seg = (inp, a, b, speed, crop, n) =>
    `[${inp}:v]trim=start=${a}:end=${b},setpts=${speed === 1 ? 'PTS-STARTPTS' : `(PTS-STARTPTS)/${speed}`},fps=25,${crop},scale=${size}:flags=lanczos,${GRADE}[s${n}]`
  return [seg(0, 0.4, 6.6, 1, crops[0], 1), seg(1, 2.5, 11.5, 1.3, crops[1], 2), seg(1, 21.0, 30.0, 1.3, crops[2], 3), seg(1, 41.0, 47.2, 1, crops[3], 4), JOIN].join(';\n')
}

function gradedMaster(name, crops, size) {
  const out = path.join(CACHE, name)
  if (fs.existsSync(out)) return out
  mkdir(CACHE)
  const gf = path.join(CACHE, `${name}.graph.txt`)
  fs.writeFileSync(gf, graph(crops, size))
  const [a, b] = manifest.videos.slice(0, 2).map((v) => path.join(SRC, 'video', v.master))
  ffmpeg(['-i', a, '-i', b, '-/filter_complex', gf, '-map', '[v]', '-an', '-c:v', 'libx264', '-preset', 'medium', '-crf', '18', '-pix_fmt', 'yuv420p', out])
  return out
}

async function webpFrom(input, out, width, quality = 78) {
  await sharp(input).resize({ width }).webp({ quality, effort: 5 }).toFile(out)
}

async function buildHero() {
  const out = path.join(PUB, 'hero')
  mkdir(out)
  const tmp = path.join(CACHE, 'tmp')
  mkdir(tmp)

  // Desktop: 16:9 crop from the left of the 4K frame, face sits left of centre with room for type on the right
  const desktop = gradedMaster('graded_desktop.mp4', Array(4).fill('crop=3840:2160:0:0'), '1920:1080')
  const scrub = (name, scale, crf) =>
    ffmpeg(['-i', desktop, '-vf', `scale=${scale}`, '-c:v', 'libx264', '-preset', 'slow', '-crf', String(crf), '-x264-params', 'keyint=8:min-keyint=8:scenecut=0:bframes=0:ref=2', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-an', path.join(out, name)])
  scrub('hero-scrub-1080.mp4', '1920:1080', 24)
  scrub('hero-scrub-720.mp4', '1280:720', 26)

  // Posters: first and last frame of the film
  ffmpeg(['-i', desktop, '-frames:v', '1', path.join(tmp, 'd-first.png')])
  ffmpeg(['-sseof', '-0.05', '-i', desktop, '-update', '1', '-frames:v', '1', path.join(tmp, 'd-last.png')])
  await webpFrom(path.join(tmp, 'd-first.png'), path.join(out, 'hero-poster-1920.webp'), 1920, 80)
  await webpFrom(path.join(tmp, 'd-first.png'), path.join(out, 'hero-poster-960.webp'), 960, 76)
  await webpFrom(path.join(tmp, 'd-last.png'), path.join(out, 'hero-ending-1920.webp'), 1920, 80)

  // Mobile: 9:16 crops tuned per chapter around the face, then a frame sequence at 8fps
  const mobile = gradedMaster('graded_mobile.mp4', ['crop=1215:2160:1393:0', 'crop=1215:2160:1500:0', 'crop=1215:2160:1450:0', 'crop=1215:2160:950:0'], '720:1280')
  const seq = path.join(out, 'seq')
  fs.rmSync(seq, { recursive: true, force: true })
  mkdir(seq)
  const raw = path.join(tmp, 'seq')
  fs.rmSync(raw, { recursive: true, force: true })
  mkdir(raw)
  ffmpeg(['-i', mobile, '-vf', 'fps=8,scale=540:960:flags=lanczos', '-q:v', '2', path.join(raw, 'f%04d.jpg')])
  const frames = fs.readdirSync(raw).filter((f) => f.endsWith('.jpg')).sort()
  for (const f of frames) await sharp(path.join(raw, f)).webp({ quality: 58, effort: 4 }).toFile(path.join(seq, f.replace('.jpg', '.webp')))
  ffmpeg(['-i', mobile, '-frames:v', '1', path.join(tmp, 'm-first.png')])
  ffmpeg(['-sseof', '-0.05', '-i', mobile, '-update', '1', '-frames:v', '1', path.join(tmp, 'm-last.png')])
  await webpFrom(path.join(tmp, 'm-first.png'), path.join(out, 'hero-poster-mobile.webp'), 720, 78)
  await webpFrom(path.join(tmp, 'm-last.png'), path.join(out, 'hero-ending-mobile.webp'), 720, 78)

  const dur = Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', desktop]).toString())
  const meta = {
    duration: Number(dur.toFixed(3)),
    seqFrames: frames.length,
    seqFps: 8,
    videoBytes: { '1080': fs.statSync(path.join(out, 'hero-scrub-1080.mp4')).size, '720': fs.statSync(path.join(out, 'hero-scrub-720.mp4')).size },
  }
  fs.writeFileSync(path.join(ROOT, 'src', 'data', 'hero.generated.js'), `// GENERATED by scripts/media.mjs, do not edit by hand.\nexport const HERO_FILM = ${JSON.stringify(meta, null, 2)}\n`)
  console.log('hero:', meta, kb(path.join(out, 'hero-scrub-1080.mp4')))
}

/* ----------------------------------------------------------------- stills */
// Demonstration stages from the two stock sessions. [master, second, crop(w:h:x:y) in 4K px, output name]
const STILLS = [
  ['6878730_4k.mp4', 2.0, '2200:1650:800:0', 'stage-skin-before', true],
  ['6878730_4k.mp4', 11.0, '2200:1650:800:0', 'stage-skin-after', true],
  ['19884161_2k.mp4', 7.5, '1600:1200:633:200', 'stage-eyes-before', false],
  ['19884161_2k.mp4', 75.0, '1600:1200:379:160', 'stage-eyes-after', false],
]

async function buildStills() {
  const out = path.join(PUB, 'stages')
  mkdir(out)
  const tmp = path.join(CACHE, 'tmp')
  mkdir(tmp)
  for (const [master, t, crop, name, graded] of STILLS) {
    const png = path.join(tmp, `${name}.png`)
    ffmpeg(['-ss', String(t), '-i', path.join(SRC, 'video', master), '-frames:v', '1', '-vf', graded ? `crop=${crop},${GRADE}` : `crop=${crop}`, png])
    await sharp(png).resize({ width: 1400 }).webp({ quality: 80, effort: 5 }).toFile(path.join(out, `${name}.webp`))
    await sharp(png).resize({ width: 700 }).webp({ quality: 74, effort: 5 }).toFile(path.join(out, `${name}-700.webp`))
  }
  console.log('stills:', STILLS.length)
}


/* --------------------------------------------------------------------- og */
async function buildOg() {
  const src = path.join(PUB, 'hero', 'hero-ending-1920.webp')
  const overlay = Buffer.from(
    '<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">' +
      '<defs><linearGradient id="g" x1="0" x2="1"><stop offset="0" stop-color="#221917" stop-opacity=".94"/><stop offset=".55" stop-color="#221917" stop-opacity=".4"/><stop offset="1" stop-color="#221917" stop-opacity="0"/></linearGradient></defs>' +
      '<rect width="1200" height="630" fill="url(#g)"/>' +
      '<text x="72" y="468" font-family="Georgia, Times New Roman, serif" font-size="88" fill="#FAF7F2">Maison Amara</text>' +
      '<text x="76" y="522" font-family="Arial, Helvetica, sans-serif" font-size="22" letter-spacing="9" fill="#B99A6B">MAKEUP ATELIER</text>' +
      '</svg>',
  )
  await sharp(src).resize(1200, 630, { fit: 'cover', position: 'centre' }).composite([{ input: overlay }]).jpeg({ quality: 84, mozjpeg: true }).toFile(path.join(ROOT, 'public', 'og-image.jpg'))
  await sharp(path.join(ROOT, 'public', 'favicon.svg'), { density: 384 }).resize(180, 180).png().toFile(path.join(ROOT, 'public', 'apple-touch-icon.png'))
  console.log('og-image.jpg + apple-touch-icon.png written')
}

/* ---------------------------------------------------------------- licenses */
