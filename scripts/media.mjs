/* -------------------------------------------------------------------- run */
const task = process.argv[2] || 'all'
const tasks = { fetch: fetchSources, images: buildImages, hero: buildHero, stills: buildStills, og: buildOg, licenses: async () => writeLicenses() }
if (task === 'all') for (const t of ['images', 'hero', 'stills', 'og', 'licenses']) await tasks[t]()
else if (tasks[task]) await tasks[task]()
else {
  console.error('usage: node scripts/media.mjs [fetch|images|hero|stills|all]')
  process.exit(1)
}
